"""Tables and macros for the two stages added after the main run (run_8b_serial.sh R1x R2r).

  R1x  e0_{tag}_x{lang}.json   the decomposition of each model on the prompts of the other two languages
  R2r  e1_{tag}_recvall.jsonl  SyncPool and coin projection, sender and receiver, on the texts of the main table
                               that its receivers did not decode; every text must equal the main-table record

Usage:  python -I plots/make_extra.py --runs results/records --out results/tables
Writes gen/tab_xlang.tex and gen/numbers_extra.tex (\\res macros, same scheme as numbers.tex).
Exits with status 1 if a re-generated text differs from its main-table record or a receiver decoded wrong bits.
"""
import argparse, collections, json, os, sys

TAGS = ["llama31_8b", "qwen3_8b_base", "llmjp3_7p2b"]
SHORT = dict(zip(TAGS, ["llama", "qwen", "llmjp"]))
NAME = dict(zip(TAGS, ["Llama-3.1-8B", "Qwen3-8B-Base", "llm-jp-3-7.2b"]))
OWN = dict(zip(TAGS, ["en", "zh", "ja"]))
LANGS = ["en", "zh", "ja"]
KS = [16, 64, 256, 1024, 4096, 0]
KMAC = {16: "16", 64: "64", 256: "256", 1024: "1k", 4096: "4k", 0: "Full"}
TABLE_KS = [256, 0]


def cells_of(path):
    return {(0 if c["k"] == "Full" else c["k"]): c for c in json.load(open(path, encoding="utf-8"))["cells"]}


def cases(path, methods):
    out = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            r = json.loads(line)
            if r.get("kind") == "case" and r["method"] in methods:
                out[(r["method"], r["k"], r["sample"])] = r
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    macros = [r"% generated by plots/make_extra.py -- do not edit", r"\makeatletter"]
    bad = 0

    def mac(name, val):
        macros.append(r"\expandafter\def\csname res@" + name + r"\endcsname{" + val + "}")

    # ---------------- R1x: every model on every language ----------------
    grid, missing = {}, []
    for tag in TAGS:
        for lang in LANGS:
            p = os.path.join(args.runs, f"e0_{tag}.json" if lang == OWN[tag] else f"e0_{tag}_x{lang}.json")
            if os.path.exists(p):
                grid[(tag, lang)] = cells_of(p)
            else:
                missing.append(os.path.basename(p))
    if missing:
        print("[warn] R1x files missing:", ", ".join(missing))
    if grid:
        stops = [100 * c["stop"] for cells in grid.values() for c in cells.values()]
        cross = [100 * c["stop"] for (tag, lang), cells in grid.items() if lang != OWN[tag] for c in cells.values()]
        mac("all@xlang@any@stopmin", f"{min(stops):.1f}")
        mac("all@xlang@any@stopmax", f"{max(stops):.1f}")
        if cross:
            mac("all@xlang@cross@stopmin", f"{min(cross):.1f}")
            mac("all@xlang@cross@stopmax", f"{max(cross):.1f}")
        mac("all@xlang@any@cells", str(len(grid)))
        for (tag, lang), cells in grid.items():
            for k, c in cells.items():
                for part in ("root", "branch", "stop"):
                    mac(f"{SHORT[tag]}@xlang@{lang}{KMAC[k]}@{part}", f"{100 * c[part]:.1f}")
        rows = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
                r" & & \multicolumn{3}{c}{$k=256$} & \multicolumn{3}{c}{Full} \\",
                r"\cmidrule(lr){3-5}\cmidrule(l){6-8}",
                r"Model & Prompts & Root & Branch & Stop & Root & Branch & Stop \\", r"\midrule"]
        for i, tag in enumerate(TAGS):
            for lang in LANGS:
                if (tag, lang) not in grid:
                    continue
                cells = grid[(tag, lang)]
                vals = []
                for k in TABLE_KS:
                    c = cells.get(k)
                    vals += [f"{100 * c[p]:.1f}" for p in ("root", "branch", "stop")] if c else ["---"] * 3
                own = r"$^\ast$" if lang == OWN[tag] else ""
                rows.append(f"{NAME[tag] if lang == LANGS[0] else ''} & {lang.upper()}{own} & " + " & ".join(vals) + r" \\")
            if i < len(TAGS) - 1:
                rows.append(r"\addlinespace")
        rows += [r"\bottomrule", r"\end{tabular}"]
        with open(os.path.join(args.out, "tab_xlang.tex"), "w") as fh:
            fh.write("\n".join(rows) + "\n")
        print(f"R1x: {len(grid)} model x language cells, stop share {min(stops):.1f}-{max(stops):.1f}%"
              + (f" (cross-language {min(cross):.1f}-{max(cross):.1f}%)" if cross else ""))

    # ---------------- R2r: all receivers of the exact single-history methods ----------------
    METH = ("syncpool", "coin")
    tot = collections.Counter()
    per_cell = collections.Counter()
    seen_any = False
    for tag in TAGS:
        p_new = os.path.join(args.runs, f"e1_{tag}_recvall.jsonl")
        p_main = os.path.join(args.runs, f"e1_{tag}.jsonl")
        if not (os.path.exists(p_new) and os.path.exists(p_main)):
            print(f"[warn] R2r: {os.path.basename(p_new)} or the main file missing")
            continue
        seen_any = True
        new, main_ = cases(p_new, METH), cases(p_main, METH)
        for key, r in main_.items():
            m, k, s = key
            if r.get("recv_checked"):
                tot[(m, "decoded")] += 1
                per_cell[(tag, m, k)] += 1
                if not r.get("correct"):
                    tot[(m, "wrong")] += 1
        for key, r in sorted(new.items(), key=str):
            m, k, s = key
            old = main_.get(key)
            if old is None:
                print(f"[error] {tag} {key}: no main-table record"); bad += 1; continue
            if old.get("recv_checked"):
                continue                      # already counted from the main file
            # stripped records (tools/export_results.py) carry hashes instead of the text and the tokens
            def _h(rec, key): return rec.get(key + "_sha", rec.get(key))
            same = (_h(r, "text") == _h(old, "text") and _h(r, "token_ids") == _h(old, "token_ids")
                    and r["n_bits"] == old["n_bits"])
            if not same:
                print(f"[error] {tag} {key}: re-generated text differs from the main-table record"); bad += 1
                tot[(m, "differs")] += 1
                continue
            if not r.get("recv_checked"):
                print(f"[warn] {tag} {key}: receiver not run"); continue
            tot[(m, "decoded")] += 1
            per_cell[(tag, m, k)] += 1
            if not r.get("correct"):
                print(f"[error] {tag} {key}: receiver {r.get('recv_error') or 'wrong bits'}"); bad += 1
                tot[(m, "wrong")] += 1
    if seen_any:
        for m in METH:
            cells_m = [v for (t, mm, k), v in per_cell.items() if mm == m]
            mac(f"all@recvall@{m}@decoded", f"{tot[(m, 'decoded')]:,}")
            mac(f"all@recvall@{m}@wrong", str(tot[(m, "wrong")]))
            mac(f"all@recvall@{m}@cellmin", str(min(cells_m)) if cells_m else "0")
            mac(f"all@recvall@{m}@cells", str(len(cells_m)))
            print(f"R2r: {m}: {tot[(m, 'decoded')]} texts decoded in {len(cells_m)} cells "
                  f"(min {min(cells_m) if cells_m else 0} per cell), {tot[(m, 'wrong')]} wrong, "
                  f"{tot[(m, 'differs')]} differing from the main table")
    macros.append(r"\makeatother")
    with open(os.path.join(args.out, "numbers_extra.tex"), "w") as fh:
        fh.write("\n".join(macros) + "\n")
    print("wrote numbers_extra.tex" + (" and tab_xlang.tex" if grid else ""))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
