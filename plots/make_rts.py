"""Table and macros for R11: ReTokSync on Discop, paired text by text with R10's Discop cells.

  R11  e1_{tag}_retoksync.jsonl     retoksync_adapter.py, k in {256, Full}, the first 50 texts
  R10  e1_{tag}_coder_discop.jsonl  Native, SyncPool and coin projection with Discop on the same prompts, keys, streams
  main e1_{tag}.jsonl               SyncPool at k=64 (range coder): the rate of ReTokSync's correction channel

Correction cost (the paper's two-channel design, supplement App. D: one correction text per group of 10 texts, one item
per wrong token = its position and replacement fragment): an Elias-gamma count of the wrong tokens, then for each wrong
token its position among the group's tokens and the correct bits it should carry (the receiver knows how many bits it
read from the token).  The table reports these bits as a share of the payload (the paper's own measure); carried by
SyncPool at k=64, they cost correction bits / SyncPool's BPT extra tokens (macro extratok).

Usage:  python -I plots/make_rts.py --runs results/records --out results/tables
Writes gen/tab_rts.tex and gen/numbers_rts.tex.  Exits 1 if a receiver did not match the sender's prediction.
"""
import argparse, collections, json, math, os, sys

import numpy as np

TAGS = ["llama31_8b", "qwen3_8b_base", "llmjp3_7p2b"]
SHORT = dict(zip(TAGS, ["llama", "qwen", "llmjp"]))
LANG = dict(zip(TAGS, ["EN", "ZH", "JA"]))
KS = [256, 0]
KMAC = {256: "256", 0: "Full"}
GROUP = 10
AUX_K = 64


def load(path, methods=None):
    out = {}
    if not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            r = json.loads(line)
            if r.get("kind") == "case" and (methods is None or r["method"] in methods):
                out[(r["method"], r["k"], r["sample"])] = r
    return out


def fmt_kl(x):
    """Per-step KL in the style of tab:main: three significant decimals, no leading zero."""
    if x == 0:
        return "0"
    s = f"{x:.4f}" if x < 0.01 else f"{x:.3f}"
    return s[1:] if s.startswith("0.") else s


def gamma_bits(n):
    return 2 * int(math.floor(math.log2(n))) + 1


def boot_ratio(a, b, rng, n=2000):
    """mean(a) / mean(b) with a 95% bootstrap interval, paired by text."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    idx = rng.integers(0, len(a), size=(n, len(a)))
    r = a[idx].mean(1) / b[idx].mean(1)
    return a.mean() / b.mean(), np.percentile(r, 2.5), np.percentile(r, 97.5)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    rng = np.random.default_rng(20261118)
    macros = [r"% generated by plots/make_rts.py -- do not edit", r"\makeatletter"]

    def mac(name, val):
        macros.append(r"\expandafter\def\csname res@" + name + r"\endcsname{" + val + "}")

    bad = 0
    rows, agg, aggk = [], collections.defaultdict(list), collections.defaultdict(list)
    for tag in TAGS:
        rts = load(os.path.join(args.runs, f"e1_{tag}_retoksync.jsonl"), {"retoksync"})
        r10 = load(os.path.join(args.runs, f"e1_{tag}_coder_discop.jsonl"), {"native", "syncpool", "coin"})
        main_ = load(os.path.join(args.runs, f"e1_{tag}.jsonl"), {"syncpool"})
        if not rts:
            print(f"[warn] {tag}: no R11 records")
            continue
        aux = [r["bpt"] for (m, k, s), r in main_.items() if k == AUX_K and r.get("complete")]
        bpt_aux = float(np.mean(aux)) if aux else float("nan")
        for k in KS:
            cell = sorted((s, r) for (m, kk, s), r in rts.items() if kk == k)
            if not cell:
                continue
            S = [s for s, r in cell if r["complete"]]
            R = {s: r for s, r in cell}
            mism = [s for s, r in cell if r["recv_checked"] and not r["recv_match"]]
            if mism:
                print(f"[error] {tag} k={k}: receiver differs from the sender's prediction on {mism}")
                bad += len(mism)
            n_tok = sum(R[s]["n_tokens"] for s in S)
            n_emit = sum(R[s]["n_emit"] for s in S)
            n_bits = sum(R[s]["n_bits"] for s in S)
            n_err = sum(R[s]["n_err_bits"] for s in S)
            text_err = sum(bool(R[s]["n_err_bits"]) for s in S)
            resets = sum(R[s]["n_resets"] for s in S)
            reuse = sum(R[s]["n_reuse"] for s in S)
            und = sum(R[s]["undecodable"] for s in S)
            kl_full = sum(R[s]["kl_full_sum"] for s in S) / max(n_emit, 1)
            kl_inf = sum(R[s]["kl_inf_steps"] for s in S)
            div_steps = sum(R[s]["kl_div_steps"] for s in S)
            div_texts = sum(R[s]["kl_div_steps"] > 0 for s in S)
            # correction message per group of GROUP consecutive samples
            corr = 0
            for g in sorted({s // GROUP for s in S}):
                mem = [s for s in S if s // GROUP == g]
                ntok = sum(R[s]["n_tokens"] for s in mem)
                pos = max(1, math.ceil(math.log2(max(ntok, 2))))
                errs = [e for s in mem for e in R[s]["err_tokens"]]
                corr += gamma_bits(len(errs) + 1) + sum(pos + span for _, span, _ in errs)
            extra_tok = corr / bpt_aux if bpt_aux == bpt_aux else float("nan")
            util_rts = [R[s]["util"] for s in S]
            out = dict(tag=tag, k=k, n=len(cell), complete=len(S), mism=len(mism), bpt=n_bits / max(n_tok, 1),
                       util=float(np.mean(util_rts)), ber=100 * n_err / max(n_bits, 1),
                       text_err=100 * text_err / max(len(S), 1), text_err_n=text_err,
                       resets=1000 * resets / max(n_tok, 1), reuse=1000 * reuse / max(n_tok, 1),
                       reuse_n=reuse, und=und, kl=kl_full, kl_inf_share=100 * kl_inf / max(n_emit, 1),
                       div_texts=div_texts, corr_ratio=100 * corr / max(n_bits, 1),
                       extra_tok=100 * extra_tok / max(n_tok, 1), bpt_aux=bpt_aux,
                       calls=(n_emit + sum(R[s]["replayed"] for s in S)) / max(n_tok, 1))   # model calls per token
            # paired comparison with R10's Discop cells
            for m in ("native", "syncpool", "coin"):
                pair = [(R[s]["util"], r10[(m, k, s)]["util"]) for s in S
                        if (m, k, s) in r10 and r10[(m, k, s)].get("complete") and r10[(m, k, s)].get("util") is not None]
                if pair:
                    a, b = zip(*pair)
                    out[f"ratio_{m}"] = boot_ratio(b, a, rng)       # method / ReTokSync
                    out[f"util_{m}"] = float(np.mean(b))
            nat = [r10[("native", k, s)] for s in range(50) if ("native", k, s) in r10]
            nat_chk = [r for r in nat if r.get("recv_checked")]
            out["native_fail"] = 100 * sum(not r.get("correct") for r in nat_chk) / max(len(nat_chk), 1)
            out["native_fail_n"] = sum(not r.get("correct") for r in nat_chk)
            out["native_n"] = len(nat_chk)
            if "ratio_native" in out:
                out["rts_native"] = 100 / out["ratio_native"][0]                  # ReTokSync's Util, % of Native's
            # e2e: payload over primary tokens plus the correction channel's tokens, relative to coin projection
            if "ratio_coin" in out:
                out["e2e_vs_coin"] = (1 + extra_tok / max(n_tok, 1)) * out["ratio_coin"][0]   # coin / e2e ReTokSync
                out["rts_coin"] = 1 / out["ratio_coin"][0]                        # ReTokSync / coin, primary tokens
                a, b = zip(*[(R[s]["util"], r10[("coin", k, s)]["util"]) for s in S
                             if ("coin", k, s) in r10 and r10[("coin", k, s)].get("complete")
                             and r10[("coin", k, s)].get("util") is not None])
                out["ratio_rts_coin"] = boot_ratio(a, b, rng)                     # ReTokSync / coin with interval
                out["rts_coin_e2e"] = 1 / out["e2e_vs_coin"]                      # counting the repair text's tokens
            rows.append(out)
            keys = ("ber", "text_err", "resets", "reuse", "kl", "kl_inf_share", "corr_ratio", "extra_tok",
                    "native_fail", "e2e_vs_coin", "rts_native", "rts_coin", "rts_coin_e2e", "native_n", "calls")
            for key in keys:
                if key in out:
                    agg[key].append(out[key])
                    aggk[(k, key)].append(out[key])
            if "ratio_coin" in out:
                agg["ratio_coin"].append(out["ratio_coin"][0])
                aggk[(k, "ratio_coin")].append(out["ratio_coin"][0])
            sk = f"{SHORT[tag]}@rts@{KMAC[k]}"
            mac(f"{sk}@util", f"{out['util']:.3f}"[1:] if out["util"] < 1 else f"{out['util']:.3f}")
            mac(f"{sk}@ber", f"{out['ber']:.2f}")
            mac(f"{sk}@texterr", f"{out['text_err']:.0f}")
            mac(f"{sk}@resets", f"{out['resets']:.1f}")
            mac(f"{sk}@reuse", f"{out['reuse']:.2f}")
            mac(f"{sk}@kl", fmt_kl(out["kl"]))
            mac(f"{sk}@klinf", f"{out['kl_inf_share']:.1f}")
            mac(f"{sk}@corr", f"{out['corr_ratio']:.2f}")
            mac(f"{sk}@extratok", f"{out['extra_tok']:.1f}")
            mac(f"{sk}@nativefail", f"{out['native_fail']:.0f}")
            if "ratio_coin" in out:
                mac(f"{sk}@coinratio", f"{out['ratio_coin'][0]:.2f}")
            if "rts_native" in out:
                mac(f"{sk}@rtsnative", f"{out['rts_native']:.0f}")
    fmts = {"kl": fmt_kl, "ber": "{:.2f}".format, "corr_ratio": "{:.2f}".format, "ratio_coin": "{:.2f}".format,
            "e2e_vs_coin": "{:.2f}".format, "reuse": "{:.2f}".format, "text_err": "{:.0f}".format,
            "native_fail": "{:.0f}".format, "rts_native": "{:.0f}".format, "rts_coin": "{:.2f}".format,
            "rts_coin_e2e": "{:.2f}".format, "native_n": "{:d}".format, "calls": "{:.3f}".format}
    for key, vals in agg.items():
        f = fmts.get(key, "{:.1f}".format)
        mac(f"all@rts@any@{key.replace('_', '')}min", f(min(vals)))
        mac(f"all@rts@any@{key.replace('_', '')}max", f(max(vals)))
    for (k, key), vals in aggk.items():
        f = fmts.get(key, "{:.1f}".format)
        mac(f"all@rts@{KMAC[k]}@{key.replace('_', '')}min", f(min(vals)))
        mac(f"all@rts@{KMAC[k]}@{key.replace('_', '')}max", f(max(vals)))
    if rows:
        mac("all@rts@any@n", str(min(o["complete"] for o in rows)))
        tab = [r"\begin{tabular}{@{}ll ccc c cc ccc c@{}}", r"\toprule",
               r" & & \multicolumn{3}{c}{Util$\uparrow$} & ReTokSync / & \multicolumn{2}{c}{Texts with errors (\%)} & "
               r"BER & Repair & Resets & \\",
               r"\cmidrule(lr){3-5}\cmidrule(lr){7-8}",
               r"Lang & $k$ & Native$^\ast$ & ReTokSync & Coin & Coin & Native$^\ast$ & ReTokSync & "
               r"(\%) & (\%) & /1k tok. & $D$ \\",
               r"\midrule"]
        for i, o in enumerate(rows):
            rc = o.get("ratio_rts_coin")
            rcs = rf"{rc[0]:.2f}\,{{\scriptsize[{rc[1]:.2f}, {rc[2]:.2f}]}}" if rc else "---"
            name = rf"\multirow{{2}}{{*}}{{{LANG[o['tag']]}}}" if o["k"] == KS[0] else ""
            u = lambda x: (f"{x:.3f}"[1:] if x < 1 else f"{x:.3f}") if x == x else "---"
            tab.append(f" {name} & {'Full' if o['k'] == 0 else o['k']} & {u(o.get('util_native', float('nan')))} & "
                       f"{u(o['util'])} & {u(o.get('util_coin', float('nan')))} & {rcs} & {o['native_fail']:.0f} & "
                       f"{o['text_err']:.0f} & {o['ber']:.2f} & {o['corr_ratio']:.2f} & {o['resets']:.1f} & "
                       f"{fmt_kl(o['kl'])} \\\\")
            if o["k"] == KS[-1] and i < len(rows) - 1:
                tab.append(r"\midrule")
        tab += [r"\bottomrule", r"\end{tabular}"]
        with open(os.path.join(args.out, "tab_rts.tex"), "w") as fh:
            fh.write("\n".join(tab) + "\n")
    macros.append(r"\makeatother")
    with open(os.path.join(args.out, "numbers_rts.tex"), "w") as fh:
        fh.write("\n".join(macros) + "\n")
    for o in rows:
        print(json.dumps({a: (round(b, 4) if isinstance(b, float) else
                              [round(x, 4) for x in b] if isinstance(b, tuple) else b) for a, b in o.items()}))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
